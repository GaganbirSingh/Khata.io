import chromium from '@sparticuz/chromium';
import puppeteer from 'puppeteer-core';
const B = process.env.BASE || 'http://localhost:4000';
const hash = B.endsWith('.html') ? '#' : '';
const b = await puppeteer.launch({ executablePath: await chromium.executablePath(), args: [...chromium.args.filter((a) => a !== '--single-process'), '--no-sandbox'], headless: true });
const p = await b.newPage();
await p.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }, { name: 'prefers-color-scheme', value: 'light' }]);
const fails = [];
const check = (c, m) => (c ? console.log('ok:', m) : (fails.push(m), console.log('FAIL:', m)));
const bg = () => p.evaluate(() => getComputedStyle(document.body).backgroundColor);
const theme = () => p.evaluate(() => document.documentElement.getAttribute('data-theme'));
await p.goto(B, { waitUntil: 'networkidle0' });
check((await bg()) === 'rgb(152, 191, 203)', 'light by default on a light device');
await p.click('.theme-toggle');
check((await theme()) === 'dark' && (await bg()) === 'rgb(11, 30, 48)', 'header toggle switches to raat');
check((await p.$eval('.theme-toggle', (e) => e.getAttribute('aria-label'))) === 'Switch to light mode', 'toggle label says what it will do');
await p.reload({ waitUntil: 'networkidle0' });
check((await theme()) === 'dark', 'choice kept after reload');
const paper = await p.$eval('.lp-sheet', (e) => [getComputedStyle(e).backgroundColor, getComputedStyle(e).color]);
check(paper[0] === 'rgb(236, 232, 214)' && paper[1] === 'rgb(15, 42, 68)', `paper stays paper with dark ink ${paper}`);
await p.goto(B + hash + '/welcome', { waitUntil: 'networkidle0' });
await p.evaluate(() => [...document.querySelectorAll('.auth-legal button')].find((x) => x.textContent.includes('Light mode')).click());
check((await theme()) === 'light', 'login footer toggle switches back');
// app: shop menu + settings
await p.evaluate(() => fetch('/api/auth/demo', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ acceptTerms: true, ageConfirmed: true }) }));
await p.goto(B + hash + '/app/settings', { waitUntil: 'networkidle0' });
if (hash) await p.reload({ waitUntil: 'networkidle0' });
await p.waitForSelector('[aria-label="Colour mode"]');
await p.evaluate(() => [...document.querySelectorAll('[aria-label="Colour mode"] button')].find((x) => x.textContent.includes('Raat')).click());
check((await theme()) === 'dark', 'settings Raat');
await p.evaluate(() => [...document.querySelectorAll('[aria-label="Colour mode"] button')].find((x) => x.textContent.includes('device')).click());
check((await theme()) === null && (await p.evaluate(() => localStorage.getItem('uk_theme'))) === null, 'Same as my device clears the choice');
await p.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }, { name: 'prefers-color-scheme', value: 'dark' }]);
check((await bg()) === 'rgb(11, 30, 48)', 'follows the device when it turns dark');
await p.click('.shop-menu > button');
await p.evaluate(() => [...document.querySelectorAll('.menu button')].find((x) => x.textContent.includes('Light mode')).click());
check((await theme()) === 'light' && !(await p.$('.menu')), 'shop menu toggle works and closes the menu');
await b.close();
console.log(`${fails.length} failure(s)`);
